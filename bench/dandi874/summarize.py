#!/usr/bin/env python3
"""The tables of the DANDI:000874 evaluation from bench/results/SP002/{octreg,baselines,reference}.json ->
bench/results/SP002/tables.md

Errors are the mean displacement from the authors' reference over the OCT tissue (mm). Success over the crops of one block and
condition is given with its Clopper-Pearson 95 % interval: accurate means a mean error up to 0.30 mm (two MRI voxels), correct
pose up to 1 mm.

    python bench/dandi874/summarize.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from scipy.stats import beta

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import BLOCKS, CONTRASTS, FLIP_DEG, NAMES, RESULTS, TIERS  # noqa: E402


def cp(k, n):
    lo = beta.ppf(0.025, k, n - k + 1) if k else 0.0
    hi = beta.ppf(0.975, k + 1, n - k) if k < n else 1.0
    return f"{k}/{n} ({100 * lo:.0f} to {100 * hi:.0f} %)"


def median(x):
    x = sorted(x)
    n = len(x)
    return float("nan") if not n else x[n // 2] if n % 2 else 0.5 * (x[n // 2 - 1] + x[n // 2])


def load(name):
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else []


def main():
    oc, bl, ref = load("octreg"), load("baselines"), load("reference")
    out = ["# DANDI:000874: results", "", "Generated by bench/dandi874/summarize.py from the JSON files next to this one. Errors are the",
           "mean displacement from the authors' reference over the OCT tissue. Counts of runs carry their Clopper-Pearson 95 %",
           "interval in parentheses.", ""]
    ctx = json.loads((RESULTS / "context.json").read_text(encoding="utf-8")) if (RESULTS / "context.json").is_file() else None
    if ctx:
        lo, hi = ctx["i58_face_margins_low_mm"], ctx["i58_face_margins_high_mm"]
        sh = ctx["mri_foreground_share"]
        out += ["## The crops", "", "Distance from each face of the crop to the 0.5 or 99.5 percentile of the OCT tissue placed by the reference",
                "(negative: the crop cuts the tissue), and the share of the C3 k = 0 crop that octreg's MRI foreground covers.", "",
                "| crop | face margins (mm) | MRI foreground |", "|---|---|---|",
                f"| I58, as given (OCT placed by octreg) | {min(lo + hi):.2f} to {max(lo + hi):.2f} | {100 * sh['I58']:.0f} % |"]
        for cond, (a, b) in ctx["crop_face_margins_mm"].items():
            out.append(f"| DANDI:000874 {cond}, all blocks | {a:.2f} to {b:.2f} | " +
                       (", ".join(f"block {k} {100 * v:.0f} %" for k, v in sh.items() if k != "I58") if cond == "C3" else "") + " |")
        out.append("")
    out += ["## octreg on the 5° FLASH", "",
            "| block | crops | accurate (≤ 0.30 mm) | correct pose (≤ 1 mm) | error of the correct-pose runs, median (mm) | the other runs: error (mm), rotation (°) |",
            "|---|---|---|---|---|---|"]
    for b in BLOCKS:
        for cond in ("C3", "C6", "C12", "WHOLE"):
            r = [x for x in oc if x["block"] == b and x["contrast"] == "flip2" and x["cond"] == cond]
            if not r:
                continue
            n, acc, cor = len(r), sum(x["mean_mm"] <= TIERS[0] for x in r), sum(x["mean_mm"] <= TIERS[1] for x in r)
            rest = ", ".join(f"{x['mean_mm']:.2f} at {x['rotation_deg']:.0f}°" for x in sorted(r, key=lambda x: x["mean_mm"]) if x["mean_mm"] > TIERS[0])
            ok = [x["mean_mm"] for x in r if x["mean_mm"] <= TIERS[1]]
            label = {"C3": "C3 (margin 3 mm, shift up to 2 mm)", "C6": "C6 (6 mm, 5 mm)", "C12": "C12 (12 mm, 10 mm)", "WHOLE": "whole chunk-2 MRI"}[cond]
            out.append(f"| {b} {NAMES[b]} | {label}, {n} | {cp(acc, n)} | {cp(cor, n)} | "
                       f"{f'{median(ok):.2f}' if ok else 'none'} | {rest or 'none'} |")
    out += ["", "## octreg on each chunk-2 image (C3 crop k = 0)", "",
            "| image | " + " | ".join(f"block {b}" for b in BLOCKS) + " |", "|---|" + "---|" * len(BLOCKS)]
    for c in CONTRASTS:
        cells = []
        for b in BLOCKS:
            r = [x for x in oc if x["name"] == f"s{b}_{c}_C3_k0"]
            cells.append(f"{r[0]['mean_mm']:.2f} mm, {r[0]['tier']}" if r else "")
        lab = f"FLASH {FLIP_DEG[c]}°" if c in FLIP_DEG else {"T1map": "T1 map", "PDmap": "PD map"}[c]
        out.append(f"| {lab} | " + " | ".join(cells) + " |")
    out += ["", "## Standard tools on the C3 k = 0 crop of the 5° FLASH (settings of bench/baselines/BASELINES.md)", "",
            "| method | setting | " + " | ".join(f"block {b}" for b in BLOCKS) + " | time, median (s) |", "|---|---|" + "---|" * len(BLOCKS) + "---|"]
    rows = [("octreg", "defaults", {x["block"]: x for x in oc if x["contrast"] == "flip2" and x["cond"] == "C3" and x["k"] == 0})]
    for t in dict.fromkeys(x["tool"] for x in bl):
        rows.append((t, next(x["setting"] for x in bl if x["tool"] == t), {x["block"]: x for x in bl if x["tool"] == t and x["crop"].endswith("C3_k0")}))
    for t, s, d in rows:
        cells = [f"{d[b]['mean_mm']:.2f} mm, {d[b]['rotation_deg']:.0f}°" if b in d else "" for b in BLOCKS]
        out.append(f"| {t} | {s} | " + " | ".join(cells) + f" | {median([x['seconds'] for x in d.values()]):.0f} |")
    ra = [x for x in bl if x["tool"] == "reg_aladin"]
    if ra:
        out += ["", "## NiftyReg reg_aladin on all C3 crops", "",
                "| block | crops | accurate | correct pose | error, median (mm) | error of the correct-pose runs, median (mm) |", "|---|---|---|---|---|---|"]
        for b in BLOCKS:
            r = [x for x in ra if x["block"] == b]
            ok = [x["mean_mm"] for x in r if x["mean_mm"] <= TIERS[1]]
            out.append(f"| {b} | {len(r)} | {cp(sum(x['mean_mm'] <= TIERS[0] for x in r), len(r))} | {cp(sum(x['mean_mm'] <= TIERS[1] for x in r), len(r))} | "
                       f"{median([x['mean_mm'] for x in r]):.2f} | {f'{median(ok):.2f}' if ok else 'none'} |")
    loc = [x for x in ref if x["check"] == "local"]
    if loc:
        out += ["", "## The reference against the image data: local refinements started at the reference (C3 k = 0)", "",
                "| method | " + " | ".join(f"block {b}" for b in BLOCKS) + " |", "|---|" + "---|" * len(BLOCKS)]
        for m in ("ants", "aladin", "octreg"):
            cells = [next((f"{x['mean_mm']:.2f} mm" for x in loc if x["method"] == m and x["block"] == b), "") for b in BLOCKS]
            out.append(f"| {m} | " + " | ".join(cells) + " |")
        rs = [x for x in ref if x["check"] == "restart"]
        if rs:
            done = [x for x in rs if "mean_mm" in x]
            out += ["", "mri_robust_register restarted from the reference moved by 2° and 0.5 mm, on the whole 5° FLASH:", "",
                    "| block | restarts finished | distance from the reference (mm) | within 1 mm |", "|---|---|---|---|"]
            for b in BLOCKS:
                d = sorted(x["mean_mm"] for x in done if x["block"] == b)
                out.append(f"| {b} | {len(d)} of {sum(x['block'] == b for x in rs)} | {d[0]:.2f} to {d[-1]:.2f} | {sum(v <= TIERS[1] for v in d)} |")
    (RESULTS / "tables.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    import argparse
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    main()
